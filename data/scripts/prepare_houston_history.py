"""Build a deterministic, geographically bounded demo sample from the saved 311 extract."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data/crawled/houston_flooded_houses.json"
TARGET = ROOT / "shared/houston-history.ts"


def prepare(rows, limit=150):
    candidates = []
    for row in rows:
        address = " ".join(row.get("address", "").upper().split())
        lat, lng = row.get("lat"), row.get("lng")
        if not address or not address[0].isdigit() or "&" in address or "INTERSECTION" in address:
            continue
        if not isinstance(lat, (int, float)) or not isinstance(lng, (int, float)):
            continue
        if not math.isfinite(lat) or not math.isfinite(lng) or not (29.5 < lat < 30.2 and -95.8 < lng < -95.0):
            continue
        distance = math.hypot((lat - 29.7617) * 111000, (lng + 95.3983) * 96500)
        if distance > 8000:
            continue
        candidates.append((distance, row["case_number"], address, row))
    seen_addresses, seen_points, result = set(), set(), []
    for _, _, address, row in sorted(candidates):
        point = (row["lat"], row["lng"])
        if address in seen_addresses or point in seen_points:
            continue
        seen_addresses.add(address)
        seen_points.add(point)
        result.append({"caseNumber": row["case_number"], "address": address,
                       "lat": row["lat"], "lng": row["lng"],
                       "neighborhood": row["neighborhood"], "reportedAt": row["created_at"]})
        if len(result) == limit:
            break
    if len(result) != limit:
        raise ValueError(f"Expected {limit} usable locations; found {len(result)}")
    return result


if __name__ == "__main__":
    sample = prepare(json.loads(SOURCE.read_text()))
    TARGET.write_text('// Generated by data/scripts/prepare_houston_history.py; do not hand edit.\n'
                      '// Historical report locations; all resident needs and demo activity are simulated.\n'
                      'export const HOUSTON_HISTORY = ' + json.dumps(sample, indent=2) + ' as const;\n\n'
                      'export const historicalRiderId = (caseNumber: string) => `demo-houston-history-${caseNumber}`;\n'
                      'export const historicalReport = (riderId?: string) => HOUSTON_HISTORY.find(row => historicalRiderId(row.caseNumber) === riderId);\n')
    print(f"Prepared {len(sample)} unique historical locations in {TARGET}")
